    fn projection_copies_use_typed_vertex_indices() {
        const SOURCE: usize = 0;
        const DESTINATION: usize = 1;
        const SOURCE_SCREEN: [i16; 2] = [123, -45];
        const SOURCE_DEPTH: i32 = 67_890;

        let source_projection = ProjectedVertex {
            screen: SOURCE_SCREEN,
            depth: SOURCE_DEPTH,
            clip_flags: ClipFlags::RIGHT,
        };
        let mut vertices = vec![
            ModelVertex {
                projected: source_projection,
                ..ModelVertex::default()
            },
            ModelVertex::default(),
        ];
        project_entities(
            &[],
            &mut vertices,
            &[ProjectionCopy {
                source: SOURCE,
                destination: DESTINATION,
            }],
            ProjectionCenter::default(),
        )
        .unwrap();
        assert_eq!(vertices[DESTINATION].projected, source_projection);
    }

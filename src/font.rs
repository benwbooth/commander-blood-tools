/// Draw `text` into a `width`-stride indexed framebuffer at (`x`,`y`) in `color`
/// using the game font (spaces advance without drawing). Clipped; returns end x.
pub fn draw_text_indexed(
    fb: &mut [u8],
    fb_width: usize,
    fb_height: usize,
    text: &str,
    x: usize,
    y: usize,
    color: u8,
) -> usize {
    let mut pen_x = x;
    for ch in text.chars() {
        if let Some(glyph) = subtitle_draw_glyph(ch) {
            for (gy, row) in glyph.rows.iter().enumerate() {
                let py = y + gy;
                if py >= fb_height {
                    continue;
                }
                for gx in 0..GAME_FONT_WIDTH {
                    if row & (0x80 >> gx) != 0 {
                        let px = pen_x + gx;
                        if px < fb_width {
                            fb[py * fb_width + px] = color;
                        }
                    }
                }
            }
        }
        pen_x += game_font_advance(ch);
    }
    pen_x
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The square-caps face is IN THE BINARY — it was never "a face that exists in no
    /// file". `0x30CD` selects it with `AX == 0`: xlat `DS:0x7362`, widths `DS:0x7412`,
    /// bitmaps `DS:0x7442` at a 20-byte stride (8 rows of big-endian u16 + 4 zero
    /// bytes). This asserts the shipped tables against the image byte-for-byte.
    #[test]
    fn square_caps_face_matches_the_binary_tables() {
        let exe = match std::fs::read("re/bin/BLOODPRG.EXE")
            .or_else(|_| std::fs::read("../re/bin/BLOODPRG.EXE"))
        {
            Ok(b) => b,
            Err(_) => return,
        };
        const DS: usize = 0xD420;
        const XLAT: usize = DS + 0x7362;
        const WIDTHS: usize = DS + 0x7412;
        const GLYPHS: usize = DS + 0x7442;
        const STRIDE: usize = 20;

        assert_eq!(&SQUARE_CAPS_CHAR_MAP[..], &exe[XLAT..WIDTHS], "xlat table");
        assert_eq!(
            &SQUARE_CAPS_WIDTHS[..],
            &exe[WIDTHS..WIDTHS + SQUARE_CAPS_WIDTHS.len()],
            "width table"
        );
        for (gi, (_, rows)) in SQUARE_CAPS_GLYPHS.iter().enumerate() {
            let base = GLYPHS + gi * STRIDE;
            for (r, &row) in rows.iter().enumerate() {
                let want = u16::from_be_bytes([exe[base + r * 2], exe[base + r * 2 + 1]]);
                assert_eq!(row, want, "glyph {gi} row {r}");
            }
        }

        // The xlat FOLDS CASE and carries space itself — the port must not re-add
        // either, which it used to do by hand.
        assert_eq!(square_caps_glyph_index('a'), square_caps_glyph_index('A'));
        assert_eq!(square_caps_glyph_index(' '), Some(47));

        // The advance heuristic the port used to derive (rightmost column + 1 + 2)
        // reproduces the real width table exactly — recorded because it means the old
        // widths were right even though their SOURCE was wrong.
        for (gi, (_, rows)) in SQUARE_CAPS_GLYPHS.iter().enumerate() {
            let derived = rows
                .iter()
                .filter(|&&r| r != 0)
                .map(|&r| 15 - r.trailing_zeros() as usize)
                .max()
                .map(|c| c + 1 + 2);
            if let Some(dv) = derived {
                assert_eq!(dv, SQUARE_CAPS_WIDTHS[gi] as usize, "advance for glyph {gi}");
            }
        }
    }

    /// The extracted glyphs must match `BLOODPRG.EXE` byte-for-byte (rows @0x14D28,
    /// advances @0x14CD2, ASCII→index map @0x14C22) — this is what makes the subtitle
    /// font verified-by-construction against the game (no gameplay needed). Skips if the
    /// executable isn't present in this checkout.
    #[test]
    fn glyphs_match_bloodprg_exe_byte_for_byte() {
        let exe = match std::fs::read("re/bin/BLOODPRG.EXE")
            .or_else(|_| std::fs::read("../re/bin/BLOODPRG.EXE"))
        {
            Ok(b) => b,
            Err(_) => return,
        };
        let (map, adv, rows) = (0x14c22usize, 0x14cd2usize, 0x14d28usize);
        let space_idx = exe[map + b' ' as usize];
        let mut checked = 0;
        // Verify EVERY printable ASCII char that the exe maps to a non-space glyph -
        // uppercase, lowercase, digits, and punctuation - byte-for-byte.
        for c in 33u8..127 {
            let ch = c as char;
            let idx = exe[map + c as usize];
            if idx == space_idx {
                continue;
            }
            let g = game_font_glyph(ch)
                .unwrap_or_else(|| panic!("engine missing glyph for {ch:?} (exe idx {idx})"));
            checked += 1;
            let idx = idx as usize;
            assert_eq!(g.rows, exe[rows + idx * 8..rows + idx * 8 + 8], "glyph '{ch}' rows");
            assert_eq!(g.advance as u8, exe[adv + idx], "glyph '{ch}' advance");
        }
        assert_eq!(checked, 73, "expected 73 printable non-space glyphs incl. lowercase");

        // WHOLE-TABLE check. The loop above stops at 127, which is why this test
        // passed for so long against a table truncated to 128 entries: the missing
        // range was never looked at. The real table runs to the advance table at
        // 0x14CD2, i.e. 176 bytes, and comparing all of it is what pins the length.
        assert_eq!(GAME_FONT_CHAR_MAP.len(), adv - map, "table length = map..advances");
        assert_eq!(
            &GAME_FONT_CHAR_MAP[..],
            &exe[map..adv],
            "the FULL xlat table must match the image, not just its ASCII half"
        );
    }

    /// The accented characters a 128-entry table silently dropped. Two defects
    /// compounded here: the table was short, AND strings were decoded with
    /// from_utf8_lossy, so CP437 0x82 became U+FFFD and would have been unmapped
    /// even with the full table.
    #[test]
    fn accented_characters_render_because_the_table_is_176_long() {
        for (ch, glyph) in [
            ('ü', 0x49u8), ('é', 0x44), ('ä', 0x41), ('à', 0x42), ('ç', 0x4b),
            ('ë', 0x43), ('è', 0x44), ('ï', 0x45), ('ì', 0x46), ('ö', 0x47),
            ('ò', 0x48), ('ù', 0x4a), ('¿', 0x1b), ('¡', 0x1d),
        ] {
            let b = cp437_byte(ch).unwrap_or_else(|| panic!("{ch:?} has no CP437 byte"));
            assert_eq!(GAME_FONT_CHAR_MAP[b as usize], glyph, "{ch:?} glyph index");
            assert!(game_font_glyph(ch).is_some(), "{ch:?} must render");
            assert!(game_font_advance(ch) > 0, "{ch:?} must advance the pen");
        }
        for ch in ['A', 'Z', 'a', 'z', '0', '9', '?', '!'] {
            assert_eq!(cp437_byte(ch), Some(ch as u8), "ASCII round-trips unchanged");
            assert!(game_font_glyph(ch).is_some(), "{ch:?} still renders");
        }
    }

    /// Real bytes from the shipped data files.
    #[test]
    fn cp437_decode_beats_utf8_lossy_on_real_game_bytes() {
        let porte_cles = b"porte_cl\x82s";           // SCRIPT1.DEB record 6
        assert_eq!(cp437_string(porte_cles), "porte_clés");
        assert_eq!(String::from_utf8_lossy(porte_cles), "porte_cl\u{fffd}s");
        let glycerium = b"glyc\x82rium";              // SCRIPT3.DIC, a DISPLAYED word
        assert_eq!(cp437_string(glycerium), "glycérium");
        assert!(
            cp437_string(glycerium).chars().all(|c| game_font_glyph(c).is_some()),
            "every character of a decoded word must have a glyph"
        );
    }

    #[test]
    fn draws_glyphs_and_skips_spaces() {
        let (w, h) = (64usize, 12usize);
        let mut fb = vec![0u8; w * h];
        let end = draw_text_indexed(&mut fb, w, h, "HI", 0, 0, 7);
        assert!(fb.iter().any(|&p| p == 7));
        assert!(end > 0);
        let mut fb2 = vec![0u8; w * h];
        let after = draw_text_indexed(&mut fb2, w, h, " ", 0, 0, 7);
        assert!(fb2.iter().all(|&p| p == 0));
        assert_eq!(after, GAME_FONT_SPACE_ADVANCE);
    }
}

/// The BOLD console/tutorial subtitle font, loaded from the user's
/// `BLOODPRG.EXE` (glyph bitmaps at file 0x145CA = DS:0x71AA, ascii->glyph map
/// at file 0x1451A = DS:0x70FA; verified byte-identical to the live game's
/// in-memory font). Monospace 8 px advance, 8x8 glyphs. The game draws ALL
/// on-console text (tutorial lines, prompts) with this face — the thin
/// [`GAME_FONT_GLYPHS`] face is the letterboxed-scene subtitle font.
pub struct BoldConsoleFont {
    /// ascii -> glyph index (0xFF = none).
    map: [u8; 128],
    /// 8-byte row bitmaps per glyph.
    glyphs: Vec<[u8; 8]>,
}

impl BoldConsoleFont {
    pub const GLYPH_MAP_FILE_OFFSET: usize = 0x1451A;
    pub const GLYPHS_FILE_OFFSET: usize = 0x145CA;
    pub const ADVANCE: usize = 8;

    /// Load from a BLOODPRG.EXE image. Returns None if the file is too short.
    pub fn load_from_exe(exe: &[u8]) -> Option<BoldConsoleFont> {
        let map_bytes = exe.get(Self::GLYPH_MAP_FILE_OFFSET..Self::GLYPH_MAP_FILE_OFFSET + 128)?;
        let mut map = [0xFFu8; 128];
        map.copy_from_slice(map_bytes);
        let max_glyph = map.iter().filter(|&&g| g != 0xFF).max().copied()? as usize + 1;
        let table = exe.get(Self::GLYPHS_FILE_OFFSET..Self::GLYPHS_FILE_OFFSET + max_glyph * 8)?;
        let glyphs = table
            .chunks_exact(8)
            .map(|c| {
                let mut rows = [0u8; 8];
                rows.copy_from_slice(c);
                rows
            })
            .collect();
        Some(BoldConsoleFont { map, glyphs })
    }

    /// Draw `text` at (x, y) in palette index `color`, exactly as the game's
    /// console text renderer lays glyphs out (monospace 8).
    pub fn draw(
        &self,
        fb: &mut [u8],
        fb_width: usize,
        fb_height: usize,
        text: &str,
        x: usize,
        y: usize,
        color: u8,
    ) {
        let mut pen = x;
        for ch in text.chars() {
            let code = ch as usize;
            if code < 128 {
                let gi = self.map[code];
                if gi != 0xFF {
                    if let Some(rows) = self.glyphs.get(gi as usize) {
                        for (gy, row) in rows.iter().enumerate() {
                            for gx in 0..8 {
                                if row & (0x80 >> gx) != 0 {
                                    let (px, py) = (pen + gx, y + gy);
                                    if px < fb_width && py < fb_height {
                                        fb[py * fb_width + px] = color;
                                    }
                                }
                            }
                        }
                    }
                }
            }
            pen += Self::ADVANCE;
        }
    }
}


//! Game font glyphs + text drawing for the runnable engine — the 8x8 bitmap font
//! extracted from `BLOODPRG.EXE` (glyph map @0x14C22, advances @0x14CD2, rows
//! @0x14D28) plus the subtitle/text draw. Lib-accessible copy of the historically-
//! verified font in `src/extract/render.rs` (unify in a later pass).

pub const GAME_FONT_WIDTH: usize = 8;
pub const GAME_FONT_HEIGHT: usize = 8;
pub const GAME_FONT_LINE_HEIGHT: usize = 8;
pub const GAME_FONT_SPACE_ADVANCE: usize = 6;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct GameFontGlyph {
    pub rows: [u8; GAME_FONT_HEIGHT],
    pub advance: usize,
}

/// The glyph to blit for a subtitle character. Unknown glyphs fall back to '?'
/// so garbage is visible, BUT a space (' ') draws NOTHING (returns None) — the
/// game's `render_string` (BLOODPRG.EXE @0x31D7) skips the space glyph and only
/// advances DI by 6. Without this, `game_font_glyph(' ')` (None, no space glyph)
/// fell through to the '?' fallback and rendered every space as '?'. Verified
/// against a real playthrough (spaces were showing as '?' in generated subtitles).
pub fn subtitle_draw_glyph(ch: char) -> Option<GameFontGlyph> {
    if ch == ' ' {
        return None;
    }
    // An UNMAPPED char is skipped entirely (render_string 0x31CE: `xlatb; or al,al;
    // js` -> no glyph, no advance), NOT shown as '?'. Space stays a 6px no-draw
    // advance (handled above / in game_font_advance).
    game_font_glyph(ch)
}

/// CP437 code for `ch`, restricted to the range the font table covers (`0x00..0xAF`).
///
/// The game's strings are CP437 bytes, and `GAME_FONT_CHAR_MAP` is indexed by that
/// BYTE. A Unicode scalar cannot index it directly: `é` decodes to U+00E9 = 233,
/// which is past the 176-entry table, so an accented character would look unmapped
/// and be skipped. This maps back to the byte the table expects.
pub fn cp437_byte(ch: char) -> Option<u8> {
    if (ch as u32) < 0x80 {
        return Some(ch as u8);
    }
    // Only 0x80..0xAF matters: the table ends at 0xB0, where CP437's box-drawing
    // characters begin and the game has no glyphs.
    (0x80u8..0xb0).find(|&b| cp437_char(b) == ch)
}

/// Decode game data (CP437) to a `String`. `String::from_utf8_lossy` is WRONG for
/// these bytes: `0x82` is `é` in CP437 but an invalid UTF-8 lead byte, so it becomes
/// U+FFFD and the character is lost before it ever reaches the font.
pub fn cp437_string(bytes: &[u8]) -> String {
    bytes.iter().map(|&b| cp437_char(b)).collect()
}

/// CP437 byte -> Unicode scalar. ASCII is identity; `0x80..0xAF` is the span the
/// font has glyphs for; above that the game has no glyph, so it maps to U+FFFD and
/// stays visible rather than silently vanishing.
fn cp437_char(b: u8) -> char {
    const HIGH: [char; 48] = [
        'Ç', 'ü', 'é', 'â', 'ä', 'à', 'å', 'ç', 'ê', 'ë', 'è', 'ï', 'î', 'ì', 'Ä', 'Å',
        'É', 'æ', 'Æ', 'ô', 'ö', 'ò', 'û', 'ù', 'ÿ', 'Ö', 'Ü', '¢', '£', '¥', '₧', 'ƒ',
        'á', 'í', 'ó', 'ú', 'ñ', 'Ñ', 'ª', 'º', '¿', '⌐', '¬', '½', '¼', '¡', '«', '»',
    ];
    if b < 0x80 {
        b as char
    } else if b < 0xb0 {
        HIGH[(b - 0x80) as usize]
    } else {
        '\u{fffd}'
    }
}

pub fn game_font_glyph(ch: char) -> Option<GameFontGlyph> {
    let code = cp437_byte(ch)? as usize;
    let idx = *GAME_FONT_CHAR_MAP.get(code)?;
    if idx == 0xff {
        return None;
    }
    let idx = idx as usize;
    Some(GameFontGlyph {
        rows: GAME_FONT_GLYPHS[idx],
        advance: GAME_FONT_WIDTHS[idx] as usize,
    })
}

pub fn game_font_advance(ch: char) -> usize {
    if ch == ' ' {
        return GAME_FONT_SPACE_ADVANCE;
    }
    // Unmapped -> advance 0 (the char is skipped, no pen movement), not a '?' or
    // space width — matches render_string's `js 0x31ce` skip.
    game_font_glyph(ch).map(|glyph| glyph.advance).unwrap_or(0)
}

/// The width the string draw REPORTS in `gs:0x27CD` — which is NOT the pen
/// distance. The draw entry (`0x3192`) zeroes the accumulator, and only the
/// glyph path adds to it (`add word gs:[0x27cd],ax` @ `0x3215`, `ax` = that
/// glyph's advance). The two other paths both skip it:
///
/// ```text
///   0x31D3  cmp al,0x20 / jne         a SPACE does `add di,6` and jumps back
///   0x31D7  add di,6 / jmp 0x31CE     -- pen moves, accumulator does NOT
///   0x31DE  or al,al / js 0x31CE      an unmapped byte is skipped entirely
/// ```
///
/// So a trailing space contributes nothing here even though it moves the pen.
/// Callers that lay out from this width — `location_panel_rows`, which places
/// the location name at `x + width + 6` (`0x9188`) — depend on that.
pub fn game_font_drawn_width(text: &str) -> usize {
    text.chars()
        .filter(|&ch| ch != ' ')
        .map(|ch| game_font_glyph(ch).map(|g| g.advance).unwrap_or(0))
        .sum()
}

